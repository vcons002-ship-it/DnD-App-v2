import {test,expect} from '@playwright/test';

test('roller opens the current 3D die for rotation, strength previews and mobile inspection',async({page},info)=>{
 test.setTimeout(90000);
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error'&&/shader|WebGL|THREE/.test(m.text()))errors.push(m.text());});
 await page.setViewportSize({width:1150,height:1000});await page.goto('/dice-comparison.html');
 await expect(page.locator('#tray')).toHaveAttribute('data-state','settled',{timeout:45000});
 await page.getByLabel('Character',{exact:true}).selectOption('2');
 await page.getByRole('button',{name:'d4',exact:true}).click();
 await expect(page.locator('#tray')).toHaveAttribute('data-state','settled',{timeout:45000});
 await page.getByRole('button',{name:'3D inspector',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'3D dice inspector'}),view=dialog.locator('.inspector-view');
 await expect(dialog).toBeVisible();await expect(view).toHaveAttribute('data-character','Vanec');
 await expect(page.getByLabel('Inspector die',{exact:true})).toHaveValue('4');
 await page.getByLabel('Inspector auto rotate').uncheck();
 const camera=await view.getAttribute('data-camera'),bounds=(await view.boundingBox())!;
 await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+bounds.height*.5);await page.mouse.down();
 await page.mouse.move(bounds.x+bounds.width*.7,bounds.y+bounds.height*.55,{steps:12});await page.mouse.up();
 await expect(view).not.toHaveAttribute('data-camera',camera!);
 await page.getByLabel('Inspector result').evaluate((input:HTMLInputElement)=>{input.value='4';input.dispatchEvent(new Event('input'));});
 await expect(dialog.locator('output')).toContainText('4 / 4');
 await page.screenshot({path:info.outputPath('vanec-d4-inspector.png')});
 await page.getByLabel('Inspector character',{exact:true}).selectOption('3');
 await page.getByLabel('Inspector die',{exact:true}).selectOption('100');
 await page.getByLabel('Inspector gold dice').check();await expect(view).toHaveAttribute('data-gold','true');
 await page.getByLabel('Inspector lighting').selectOption('studio');
 await page.getByRole('button',{name:'Close dice inspector'}).click();await expect(dialog).not.toBeVisible();
 await expect(page.locator('#tray')).toHaveAttribute('data-state','settled');
 await page.setViewportSize({width:430,height:932});
 await page.getByRole('button',{name:'3D inspector',exact:true}).click();await expect(dialog).toBeVisible();
 expect(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('mobile-dice-inspector.png')});
 await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible();
 expect(errors).toEqual([]);
});
