const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});page.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url())});
 await page.goto('https://dnd.nic024i.app/uploads/previews/darkvision-interactive-20260928/index.html');
 await page.getByText('7/7 miniatures loaded',{exact:true}).waitFor({timeout:180000});
 await page.getByRole('button',{name:'Heavy darkness',exact:true}).click();
 await page.locator('[data-testid="player-vision"][data-heavy="true"]').waitFor();
 await page.screenshot({path:'artifacts/darkvision-interactive-mobile.png'});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 const cover=page.locator('[data-testid="player-vision"] > div').nth(1);
 const before=await cover.getAttribute('style');
 await page.getByRole('button',{name:'Move party',exact:true}).click();
 await page.waitForTimeout(1500);const during=await cover.getAttribute('style');
 await page.getByRole('button',{name:'Move party',exact:true}).waitFor({timeout:20000});
 await page.getByRole('button',{name:'Lanterns off',exact:true}).click();
 await page.getByRole('button',{name:'Placed lights',exact:true}).click();
 await page.getByLabel('View as',{exact:true}).selectOption('varis');
 await page.getByRole('button',{name:'Overhead view'}).click();await page.waitForTimeout(800);
 await page.screenshot({path:'artifacts/darkvision-interactive-mobile-unlit.png'});
 await page.getByLabel('View as',{exact:true}).selectOption('dm');
 if(await page.getByTestId('player-vision').count())throw Error('DM mask still shown');
 await page.getByLabel('View as',{exact:true}).selectOption('vanec');
 await page.getByTestId('player-vision').waitFor();
 await page.getByRole('button',{name:'Lanterns on',exact:true}).click();
 await page.getByRole('button',{name:'Regular darkness',exact:true}).click();
 await page.locator('[data-testid="player-vision"][data-heavy="false"]').waitFor();
 await page.setViewportSize({width:1440,height:1000});await page.waitForTimeout(1000);
 await page.getByRole('button',{name:'Zoom in',exact:true}).click();await page.waitForTimeout(800);
 await page.getByRole('button',{name:'Rotate view',exact:true}).click();await page.waitForTimeout(800);
 const rotation=Number(await page.getByTestId('environment-stage').getAttribute('data-view-rotation'));
 if(!(rotation>1))throw Error('Camera did not rotate');
 await page.getByRole('button',{name:'Rotate view',exact:true}).click();
 await page.screenshot({path:'artifacts/darkvision-interactive-desktop.png'});
 const result={overflow,maskMoved:before!==during,errors};console.log(JSON.stringify(result,null,2));
 fs.writeFileSync('artifacts/darkvision-interactive-verification.json',JSON.stringify(result,null,2));
 await browser.close();if(overflow||before===during||errors.length)process.exitCode=1;
})();
